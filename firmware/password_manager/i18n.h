// Para agregar un idioma nuevo (ej. portugués):
//   1. static const char* _i18n_pt[K_COUNT] = { ... };
//   2. agregarlo aquí: { _i18n_es, _i18n_en, _i18n_pt }
//   3. enum LANG_PT en LANG_COUNT arriba
static const char** _i18n_langs[LANG_COUNT] = { _i18n_es, _i18n_en };

// idioma activo — cacheado en RAM al boot
static int _lang = LANG_ES;

static void i18n_begin() {
    _lang = vault_get_lang();
    if (_lang < 0 || _lang >= LANG_COUNT) _lang = LANG_ES;
}

static int  i18n_get_lang()        { return _lang; }
static void i18n_set_lang(int l)   { if (l < 0 || l >= LANG_COUNT) return; _lang = l; vault_set_lang(l); }

// t(K_X) — usar en lv_label_set_text(obj, t(K_X))
static inline const char* t(int key) {
    if (key < 0 || key >= K_COUNT) return "?";
    return _i18n_langs[_lang][key];
}
